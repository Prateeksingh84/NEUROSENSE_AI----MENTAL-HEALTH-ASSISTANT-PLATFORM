def _safe(value: Any, default: str = "—") -> str:
    if value is None:
        return default

    text = str(value).strip()

    return text if text else default


def _shorten(value: Any, max_len: int = 90) -> str:
    text = _safe(value)

    if len(text) <= max_len:
        return text

    return text[: max_len - 3].rstrip() + "..."


def _section(story, styles, title: str):
    story.append(Paragraph(title, styles["NS_Section"]))


def _paragraph(story, styles, text: str):
    story.append(Paragraph(_escape_text(_safe(text)), styles["NS_Normal"]))


def _bullet_list(story, styles, items: List[str]):
    if not items:
        story.append(Paragraph("No data available.", styles["NS_Normal"]))
        return

    for item in items:
        story.append(Paragraph(f"• {_escape_text(_safe(item))}", styles["NS_Normal"]))


def _escape_text(value: Any) -> str:
    """
    Escape text for ReportLab Paragraph.
    Also preserves line breaks.
    """

    text = _safe(value)
    text = html.escape(text)
    text = text.replace("\n", "<br/>")
    return text


def _cell(value: Any, style):
    """
    Convert table cell text into ReportLab Paragraph so long text wraps properly.
    """

    return Paragraph(_escape_text(value), style)


def _table(data, col_widths=None):
    """
    ReportLab Table with Paragraph cells.

    This prevents overlapping text in PDF tables because Paragraph cells wrap
    within column width, while plain strings can overflow.
    """

    styles = _styles()

    cell_style = ParagraphStyle(
        name="NS_Table_Cell",
        parent=styles["NS_Normal"],
        fontName="Helvetica",
        fontSize=8.0,
        leading=10.5,
        textColor=BLACK,
        wordWrap="CJK",
        spaceAfter=0,
    )

    header_style = ParagraphStyle(
        name="NS_Table_Header",
        parent=styles["NS_Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.3,
        leading=10.5,
        textColor=BLACK,
        wordWrap="CJK",
        spaceAfter=0,
    )

    wrapped_data = []

    for row_index, row in enumerate(data):
        wrapped_row = []

        for cell in row:
            wrapped_row.append(
                _cell(
                    cell,
                    header_style if row_index == 0 else cell_style
                )
            )

        wrapped_data.append(wrapped_row)

    table = Table(
        wrapped_data,
        colWidths=col_widths,
        hAlign="LEFT",
        repeatRows=1,
        splitByRow=True,
    )

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), SOFT_PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), BLACK),
        ("TEXTCOLOR", (0, 1), (-1, -1), BLACK),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT_BG]),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))

    return table


