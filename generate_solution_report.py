def generate_solution_csv(user_data: Dict[str, Any], output_path: str) -> bool:
    """
    Generate Solution / Wellness Plan CSV.

    Required by generate_report.py:
        from generate_solution_report import generate_solution_csv
    """

    suggestions = _safe_suggestions(user_data)
    professional_help = _professional_help(user_data)
    checkin_summary = _checkin_summary(user_data)

    rows = [
        ["Section", "Field", "Value"],
        ["Summary", "Name", user_data.get("name", "User")],
        ["Summary", "Wellbeing Score", checkin_summary.get("wellbeing_score", "—")],
        ["Summary", "Risk Level", checkin_summary.get("risk_level", "unknown")],
        ["Summary", "Dominant Emotion", user_data.get("top_emotion", "neutral")],
        ["Summary", "Disclaimer", DISCLAIMER],
    ]

    for idx, item in enumerate(suggestions[:5], start=1):
        rows.append([f"Top Suggestion {idx}", "Title", item.get("title", "")])
        rows.append([f"Top Suggestion {idx}", "Why", item.get("why") or item.get("description", "")])
        rows.append([f"Top Suggestion {idx}", "How To Do", item.get("how_to_do") or item.get("description", "")])
        rows.append([f"Top Suggestion {idx}", "Frequency", item.get("frequency", "")])

    rows.append(["Professional Help", "Needed", professional_help.get("needs_professional_help", False)])
    rows.append(["Professional Help", "Urgency", professional_help.get("urgency", "none")])
    rows.append(["Professional Help", "Message", professional_help.get("user_facing_message", "")])

    for rec in professional_help.get("recommendations", []) or []:
        rows.append(["Professional Recommendation", "Issue", rec.get("issue", "")])
        rows.append(["Professional Recommendation", "Professional", rec.get("professional", "")])
        rows.append(["Professional Recommendation", "Urgency", rec.get("urgency", "")])
        rows.append(["Professional Recommendation", "Reason", rec.get("reason", "")])

    for resource in professional_help.get("resources", []) or []:
        rows.append(["Resource", "Name", resource.get("name", "")])
        rows.append(["Resource", "Phone", resource.get("phone", "")])
        rows.append(["Resource", "Alternate Phone", resource.get("alternate_phone", "")])
        rows.append(["Resource", "WhatsApp", resource.get("whatsapp", "")])
        rows.append(["Resource", "Email", resource.get("email", "")])
        rows.append(["Resource", "Website", resource.get("website", "")])
        rows.append(["Resource", "Available", resource.get("available", "")])

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    return os.path.exists(output_path) and os.path.getsize(output_path) > 0


