def generate_solution_pdf(user_data: Dict[str, Any], output_path: str) -> bool:
    """
    Generate Solution / Wellness Plan PDF.

    Required by generate_report.py:
        from generate_solution_report import generate_solution_pdf
    """

    styles = _styles()

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=0.40 * inch,
        leftMargin=0.40 * inch,
        topMargin=0.50 * inch,
        bottomMargin=0.50 * inch,
        title="NeuroSense AI Wellness Plan",
    )

    story = []

    report_date = user_data.get("report_date") or datetime.date.today().strftime("%d %B %Y")
    report_id = user_data.get("report_id") or f"NSP-{datetime.datetime.now().strftime('%Y%m%d%H%M')}"

    suggestions = _safe_suggestions(user_data)
    professional_help = _professional_help(user_data)
    checkin_summary = _checkin_summary(user_data)

    story.append(Paragraph("NeuroSense AI", styles["NS_Title"]))
    story.append(Paragraph("Personalized Wellness & Support Plan", styles["NS_Title"]))
    story.append(Paragraph(
        f"Report ID: {_escape_text(report_id)} &nbsp;&nbsp; | &nbsp;&nbsp; Generated: {_escape_text(report_date)}",
        styles["NS_Subtitle"],
    ))

    story.append(Paragraph(_escape_text(DISCLAIMER), styles["NS_Disclaimer"]))

    # -------------------------------------------------------------------------
    # 1. Current Support Summary
    # -------------------------------------------------------------------------

    _section(story, styles, "1. Current Support Summary")

    _paragraph(
        story,
        styles,
        checkin_summary.get("summary", "No wellbeing check-in is available yet.")
    )

    support_rows = [
        ["Field", "Value"],
        ["Wellbeing Score", _safe(checkin_summary.get("wellbeing_score"))],
        ["Risk / Support Need", _safe(checkin_summary.get("risk_level")).upper()],
        ["Dominant Emotion", _safe(user_data.get("top_emotion", "neutral")).capitalize()],
        ["Average Mood", f"{_safe(user_data.get('avg_mood'))}/10"],
    ]

    story.append(_table(
        support_rows,
        [2.1 * inch, 4.8 * inch],
    ))

    story.append(Spacer(1, 8))

    # -------------------------------------------------------------------------
    # 2. Top 5 Suggestions
    # -------------------------------------------------------------------------

    _section(story, styles, "2. Top 5 Personalized Suggestions")

    suggestion_rows = [["#", "Suggestion", "Why", "How To Do", "Frequency"]]

    for idx, item in enumerate(suggestions[:5], start=1):
        frequency = _shorten(item.get("frequency"), 28)

        suggestion_rows.append([
            str(idx),
            _shorten(item.get("title"), 34),
            _shorten(item.get("why") or item.get("description"), 125),
            _shorten(item.get("how_to_do") or item.get("description"), 150),
            frequency,
        ])

    story.append(_table(
        suggestion_rows,
        [
            0.32 * inch,   # #
            1.25 * inch,   # Suggestion
            1.75 * inch,   # Why
            2.45 * inch,   # How To Do
            1.10 * inch,   # Frequency
        ],
    ))

    story.append(Spacer(1, 8))

    # -------------------------------------------------------------------------
    # 3. Daily Practices
    # -------------------------------------------------------------------------

    _section(story, styles, "3. Daily Practices")

    daily_practices = [
        "Start the day with one 2-minute breathing exercise.",
        "Write one mood note: what happened, what I felt, what I need.",
        "Take one small action that supports your routine.",
        "Reduce screen exposure before sleep when possible.",
        "Check in with one trusted person if you feel isolated.",
    ]

    _bullet_list(story, styles, daily_practices)

    # -------------------------------------------------------------------------
    # 4. Grounding Exercises
    # -------------------------------------------------------------------------

    _section(story, styles, "4. Grounding & Emotional Regulation")

    grounding = [
        "5-4-3-2-1 grounding: notice 5 things you see, 4 you feel, 3 you hear, 2 you smell, and 1 you taste.",
        "Box breathing: breathe in for 4, hold for 4, breathe out for 4, hold for 4.",
        "Emotion naming: say, “I am noticing this feeling, and it makes sense because...”",
        "Small-step reset: choose one task that takes less than 5 minutes.",
    ]

    _bullet_list(story, styles, grounding)

    # -------------------------------------------------------------------------
    # 5. Sleep Support
    # -------------------------------------------------------------------------

    _section(story, styles, "5. Sleep & Recovery Support")

    sleep_support = [
        "Keep a consistent sleep and wake time when possible.",
        "Avoid heavy emotional problem-solving right before sleep.",
        "Write tomorrow’s tasks before bed to reduce mental load.",
        "Use a calm wind-down routine: dim lights, slow breathing, low stimulation.",
    ]

    _bullet_list(story, styles, sleep_support)

    # -------------------------------------------------------------------------
    # 6. Social Support
    # -------------------------------------------------------------------------

    _section(story, styles, "6. Social Support Plan")

    social_support = [
        "Identify one trusted person you can message or call.",
        "Use a simple message: “I’m having a difficult day. Can we talk for a few minutes?”",
        "If direct conversation feels hard, try text or voice note first.",
        "If you do not have support available, consider a counselling helpline.",
    ]

    _bullet_list(story, styles, social_support)

    # -------------------------------------------------------------------------
    # 7. Professional Help
    # -------------------------------------------------------------------------

    _section(story, styles, "7. Professional Help Outside NeuroSense AI")

    if compact_professional_help_summary:
        try:
            _paragraph(story, styles, compact_professional_help_summary(professional_help))
        except Exception:
            _paragraph(
                story,
                styles,
                professional_help.get(
                    "user_facing_message",
                    "Professional help can be considered if distress continues."
                )
            )
    else:
        _paragraph(
            story,
            styles,
            professional_help.get(
                "user_facing_message",
                "Professional help can be considered if distress continues."
            )
        )

    recommendations = professional_help.get("recommendations", []) or []

    if recommendations:
        rec_rows = [["Issue", "Suggested Professional", "Urgency", "Reason"]]

        for rec in recommendations:
            rec_rows.append([
                _shorten(rec.get("issue"), 40),
                _shorten(rec.get("professional"), 55),
                _shorten(rec.get("urgency"), 20),
                _shorten(rec.get("reason"), 150),
            ])

        story.append(_table(
            rec_rows,
            [
                1.1 * inch,
                1.65 * inch,
                0.9 * inch,
                3.2 * inch,
            ],
        ))
    else:
        _paragraph(
            story,
            styles,
            "No urgent professional referral signal was detected from available data. "
            "The user may still choose professional support if needed."
        )

    story.append(Spacer(1, 8))

    # -------------------------------------------------------------------------
    # 8. Resources
    # -------------------------------------------------------------------------

    _section(story, styles, "8. Verified Support Resources")

    resources = professional_help.get("resources", []) or []

    if format_resources_for_report and resources:
        try:
            resource_lines = format_resources_for_report(resources)
        except Exception:
            resource_lines = CRISIS_RESOURCES
    else:
        resource_lines = CRISIS_RESOURCES

    _bullet_list(story, styles, resource_lines)

    story.append(Paragraph(_escape_text(DISCLAIMER), styles["NS_Disclaimer"]))

    doc.build(story)

    return os.path.exists(output_path) and os.path.getsize(output_path) > 0


