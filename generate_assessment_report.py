def generate_assessment_csv(user_data: Dict[str, Any], output_path: str) -> bool:
    """
    Generate Assessment Report CSV.
    """

    checkin_summary = _latest_checkin_summary(user_data)
    trend_summary = _wellbeing_trend(user_data)

    rows = [
        ["Section", "Metric", "Value"],
        ["User", "Name", user_data.get("name", "User")],
        ["User", "Email", user_data.get("email", "—")],
        ["User", "Language", user_data.get("lang", "EN")],
        ["Session", "Total Sessions", user_data.get("total_sessions", 0)],
        ["Session", "Total Messages", user_data.get("total_messages", 0)],
        ["Session", "Streak", user_data.get("streak", 0)],
        ["Emotion", "Dominant Emotion", user_data.get("top_emotion", "neutral")],
        ["Mood", "Average Mood", user_data.get("avg_mood", "—")],
        ["Wellbeing", "Latest Score", checkin_summary.get("wellbeing_score", "—")],
        ["Wellbeing", "Risk Level", checkin_summary.get("risk_level", "unknown")],
        ["Wellbeing", "Trend", trend_summary.get("trend", "limited_data")],
        ["Wellbeing", "Summary", checkin_summary.get("summary", "No data")],
        ["Conversation", "Summary", _conversation_summary(user_data)],
        ["Disclaimer", "Safety", DISCLAIMER],
    ]

    emotion_freq = user_data.get("emotion_freq", {}) or {}

    for emotion, count in emotion_freq.items():
        rows.append(["Emotion Breakdown", emotion, count])

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    return os.path.exists(output_path) and os.path.getsize(output_path) > 0