def _emotion_breakdown(user_data: Dict[str, Any]) -> List[List[str]]:
    emotion_freq = user_data.get("emotion_freq", {}) or {}

    if not emotion_freq:
        return [["Emotion", "Count", "Percentage"], ["No emotion data", "0", "0%"]]

    total = sum(emotion_freq.values()) or 1

    rows = [["Emotion", "Count", "Percentage"]]

    for emotion, count in sorted(
        emotion_freq.items(),
        key=lambda x: x[1],
        reverse=True,
    ):
        pct = round((count / total) * 100, 1)

        rows.append([
            emotion.capitalize(),
            str(count),
            f"{pct}%",
        ])

    return rows


def _latest_checkin_summary(user_data: Dict[str, Any]) -> Dict[str, Any]:
    latest = (
        user_data.get("latest_wellbeing_checkin")
        or (
            user_data.get("wellbeing_checkins", [])[-1]
            if user_data.get("wellbeing_checkins")
            else None
        )
    )

    if summarize_checkin:
        return summarize_checkin(latest)

    if not latest:
        return {
            "available": False,
            "summary": "No wellbeing check-in is available.",
            "wellbeing_score": None,
            "risk_level": "unknown",
        }

    return {
        "available": True,
        "summary": "A wellbeing check-in is available but detailed summarizer is unavailable.",
        "wellbeing_score": latest.get("wellbeing_score"),
        "risk_level": latest.get("risk_level", "unknown"),
    }


def _wellbeing_trend(user_data: Dict[str, Any]) -> Dict[str, Any]:
    checkins = user_data.get("wellbeing_checkins", []) or []

    if summarize_wellbeing_trend:
        return summarize_wellbeing_trend(checkins)

    if not checkins:
        return {
            "available": False,
            "trend": "limited_data",
            "summary": "No wellbeing check-ins are available.",
        }

    return {
        "available": True,
        "trend": "limited_data",
        "summary": f"{len(checkins)} wellbeing check-in(s) found.",
    }


def _conversation_summary(user_data: Dict[str, Any]) -> str:
    recent_sessions = user_data.get("recent_sessions", []) or []

    if not recent_sessions:
        return "No recent conversation history is available."

    user_messages = []

    for session in recent_sessions[:5]:
        for msg in session.get("messages", []):
            if msg.get("role") == "user":
                content = str(msg.get("content", "")).strip()

                if content:
                    user_messages.append(content[:180])

    if not user_messages:
        return "Recent sessions exist, but no user message content is available."

    sample = "; ".join(user_messages[:5])

    return (
        "Recent user messages indicate the following themes or concerns: "
        f"{sample}. This is an observational summary only."
    )


def _engagement_level(total_messages: int, total_sessions: int, streak: int) -> str:
    if total_messages >= 40 or total_sessions >= 8 or streak >= 7:
        return "High"

    if total_messages >= 10 or total_sessions >= 3 or streak >= 3:
        return "Moderate"

    return "Low"


