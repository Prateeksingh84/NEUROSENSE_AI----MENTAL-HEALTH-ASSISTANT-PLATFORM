def generate_assessment_pdf(user_data: Dict[str, Any], output_path: str) -> bool:
    """
    Generate Assessment Report PDF.
    """

    styles = _styles()

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=0.55 * inch,
        leftMargin=0.55 * inch,
        topMargin=0.55 * inch,
        bottomMargin=0.55 * inch,
        title="NeuroSense AI Assessment Report",
    )

    story = []

    report_date = user_data.get("report_date") or datetime.date.today().strftime("%d %B %Y")
    report_id = user_data.get("report_id") or f"NSA-{datetime.datetime.now().strftime('%Y%m%d%H%M')}"

    story.append(Paragraph("NeuroSense AI", styles["NS_Title"]))
    story.append(Paragraph("Mental Wellness Assessment Report", styles["NS_Title"]))
    story.append(Paragraph(
        f"Report ID: {report_id} &nbsp;&nbsp; | &nbsp;&nbsp; Generated: {report_date}",
        styles["NS_Subtitle"],
    ))

    story.append(Paragraph(DISCLAIMER, styles["NS_Disclaimer"]))

    # -------------------------------------------------------------------------
    # User Overview
    # -------------------------------------------------------------------------

    _section(story, styles, "1. User & Session Overview")

    total_messages = int(user_data.get("total_messages", 0) or 0)
    total_sessions = int(user_data.get("total_sessions", 0) or 0)
    streak = int(user_data.get("streak", 0) or 0)
    avg_mood = user_data.get("avg_mood", "—")
    top_emotion = user_data.get("top_emotion", "neutral")

    overview_rows = [
        ["Field", "Value"],
        ["Name", _safe(user_data.get("name", "User"))],
        ["Email", _safe(user_data.get("email"))],
        ["Language", _safe(user_data.get("lang"))],
        ["Total Sessions", str(total_sessions)],
        ["Total Messages", str(total_messages)],
        ["Engagement Streak", f"{streak} day(s)"],
        ["Average Mood Score", f"{avg_mood}/10"],
        ["Dominant Detected Emotion", _safe(top_emotion).capitalize()],
        ["Engagement Level", _engagement_level(total_messages, total_sessions, streak)],
    ]

    story.append(_table(overview_rows, [2.2 * inch, 4.7 * inch]))

    # -------------------------------------------------------------------------
    # Emotion Analysis
    # -------------------------------------------------------------------------

    _section(story, styles, "2. Detected Emotion Patterns")

    story.append(_table(_emotion_breakdown(user_data), [2.3 * inch, 1.5 * inch, 2.1 * inch]))

    emotion_summary = (
        f"The most frequently detected emotion is {_safe(top_emotion).capitalize()}. "
        "This pattern is based on available emotion detection logs and should be treated "
        "as supportive context, not a diagnosis."
    )

    _paragraph(story, styles, emotion_summary)

    # -------------------------------------------------------------------------
    # Mood Trend
    # -------------------------------------------------------------------------

    _section(story, styles, "3. Mood Trend")

    mood_timeline = user_data.get("mood_timeline", []) or []
    daily_labels = user_data.get("daily_labels", []) or []

    mood_rows = [["Date", "Mood Score"]]

    if mood_timeline and daily_labels:
        for label, score in zip(daily_labels, mood_timeline):
            mood_rows.append([label, _safe(score, "No data")])
    else:
        mood_rows.append(["No data", "No data"])

    story.append(_table(mood_rows, [2.2 * inch, 2.2 * inch]))

    valid_mood = [x for x in mood_timeline if x is not None]

    if len(valid_mood) >= 2:
        if valid_mood[-1] > valid_mood[0]:
            trend = "improving"
        elif valid_mood[-1] < valid_mood[0]:
            trend = "declining"
        else:
            trend = "stable"
    else:
        trend = "limited data"

    _paragraph(
        story,
        styles,
        f"The observed mood trend is {trend}. This is calculated from available emotion-based mood scores only.",
    )

    # -------------------------------------------------------------------------
    # Wellbeing Check-in
    # -------------------------------------------------------------------------

    _section(story, styles, "4. Mental & Social Wellbeing Check-In")

    checkin_summary = _latest_checkin_summary(user_data)
    trend_summary = _wellbeing_trend(user_data)

    latest_score = checkin_summary.get("wellbeing_score", "—")
    risk_level = checkin_summary.get("risk_level", "unknown")

    checkin_rows = [
        ["Field", "Value"],
        ["Latest Wellbeing Score", _safe(latest_score)],
        ["Risk / Support Need Level", _safe(risk_level).upper()],
        ["Trend", _safe(trend_summary.get("trend", "limited_data"))],
        ["Check-in Summary", _safe(checkin_summary.get("summary"))],
    ]

    story.append(_table(checkin_rows, [2.2 * inch, 4.7 * inch]))

    _paragraph(story, styles, _safe(trend_summary.get("summary")))

    # -------------------------------------------------------------------------
    # Conversation History Summary
    # -------------------------------------------------------------------------

    _section(story, styles, "5. Conversation History Summary")

    _paragraph(story, styles, _conversation_summary(user_data))

    # -------------------------------------------------------------------------
    # Engagement Patterns
    # -------------------------------------------------------------------------

    _section(story, styles, "6. Engagement Patterns")

    daily_labels = user_data.get("daily_labels", []) or []
    daily_counts = user_data.get("daily_counts", []) or []

    engagement_rows = [["Date", "Messages"]]

    if daily_labels and daily_counts:
        for label, count in zip(daily_labels, daily_counts):
            engagement_rows.append([label, str(count)])
    else:
        engagement_rows.append(["No data", "0"])

    story.append(_table(engagement_rows, [2.2 * inch, 2.2 * inch]))

    engagement_summary = (
        f"The user's engagement level is {_engagement_level(total_messages, total_sessions, streak)} "
        f"based on {total_sessions} session(s), {total_messages} message(s), and a {streak}-day streak."
    )

    _paragraph(story, styles, engagement_summary)

    # -------------------------------------------------------------------------
    # Risk / Limitations
    # -------------------------------------------------------------------------

    _section(story, styles, "7. Risk Level & Limitations")

    risk_text = (
        f"Current support-need risk level: {risk_level}. "
        "This risk level is based on the wellbeing check-in and available interaction data. "
        "It is not a clinical risk assessment."
    )

    story.append(Paragraph(risk_text, styles["NS_Bold"]))
    story.append(Spacer(1, 8))
    story.append(Paragraph(DISCLAIMER, styles["NS_Disclaimer"]))

    doc.build(story)

    return os.path.exists(output_path) and os.path.getsize(output_path) > 0


