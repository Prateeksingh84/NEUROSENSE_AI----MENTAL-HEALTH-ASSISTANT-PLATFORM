def _safe(value: Any, default: str = "—") -> str:
    if value is None:
        return default

    text = str(value).strip()

    return text if text else default


def _risk_color(risk: str):
    risk = (risk or "").lower()

    if risk == "high":
        return RED

    if risk == "medium":
        return ORANGE

    return GREEN


def _section(story, styles, title: str):
    story.append(Paragraph(title, styles["NS_Section"]))


def _paragraph(story, styles, text: str):
    story.append(Paragraph(_safe(text), styles["NS_Normal"]))


def _bullet_list(story, styles, items: List[str]):
    if not items:
        story.append(Paragraph("No data available.", styles["NS_Normal"]))
        return

    for item in items:
        story.append(Paragraph(f"• {_safe(item)}", styles["NS_Normal"]))


def _table(data, col_widths=None):
    table = Table(data, colWidths=col_widths, hAlign="LEFT")

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), SOFT_PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), BLACK),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
        ("TEXTCOLOR", (0, 1), (-1, -1), BLACK),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("GRID", (0, 0), (-1, -1), 0.6, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT_BG]),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))

    return table


